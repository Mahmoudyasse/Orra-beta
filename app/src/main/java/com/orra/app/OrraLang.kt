/** Runtime app language. Add a language: add a row to `languages` and a map to `dictionaries`. */
object OrraLang {
    val languages = listOf("system" to "System", "en" to "English", "ar" to "العربية", "fr" to "Français", "es" to "Español")
    val code = mutableStateOf("system")
    fun load(context: Context) { code.value = OrraPrefs.get(context).getString("app_lang_code", "system") ?: "system" }
    fun set(context: Context, value: String) {
        code.value = value
        OrraPrefs.get(context).edit().putString("app_lang_code", value).apply()
    }
    fun effective(): String {
        val chosen = code.value
        if (chosen != "system") return chosen
        // "system" = the original app: English text, original layout direction.
        return "en"
    }
    /** null = leave the layout direction exactly as the original app had it. */
    fun layoutOverride(): androidx.compose.ui.unit.LayoutDirection? = when (code.value) {
        "system" -> null
        "ar" -> androidx.compose.ui.unit.LayoutDirection.Rtl
        else -> androidx.compose.ui.unit.LayoutDirection.Ltr
    }
    fun nativeName(value: String, systemLabel: String): String =
        if (value == "system") systemLabel else languages.firstOrNull { it.first == value }?.second ?: value
    fun t(key: String): String {
        val lang = effective()
        return dictionaries[lang]?.get(key) ?: OrraStringsExtra.byLanguage[lang]?.get(key)
            ?: dictionaries["en"]?.get(key) ?: OrraStringsExtra.en[key] ?: key
    }

