    fun set(context: Context, value: String) {
        code.value = value
        OrraPrefs.get(context).edit().putString("app_lang_code", value).apply()
    }
    fun effective(): String {
        val chosen = code.value
        if (chosen != "system") return chosen
        val system = Locale.getDefault().language
        return if (dictionaries.containsKey(system)) system else "en"
    }
    fun isRtl(): Boolean = effective() == "ar"
    fun nativeName(value: String, systemLabel: String): String =
        if (value == "system") systemLabel else languages.firstOrNull { it.first == value }?.second ?: value
